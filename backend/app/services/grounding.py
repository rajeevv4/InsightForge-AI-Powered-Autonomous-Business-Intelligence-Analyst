import re
import logging
from typing import Any, List, Set

logger = logging.getLogger(__name__)

DEV_TO_ARABIC = str.maketrans("०१२३४५६७८९", "0123456789")

# Pattern matching formatted numbers: currency, commas (Western & Indian 2/3 digits), decimals, percentages
# Matches: R$ 13,221,498.11, R$ 12,33,131.72, 159.83, 96,478, 15.2%, 4.16, -2.5
NUMBER_REGEX = re.compile(
    r'(?:R\$\s*|₹\s*|\$\s*|Rs\.?\s*|रुपये\s*|रु\.?\s*)?(-?\b\d{1,3}(?:,\d{2,3})+(?:\.\d+)?|-?\b\d+(?:\.\d+)?)\s*(%?)',
    re.IGNORECASE
)

# Common metadata / structural numbers that should not trigger hallucination flags
COMMON_METADATA_NUMBERS = {
    # Zeroes and neutral scale values
    0.0,
    # Years in Olist dataset and modern era
    2016.0, 2017.0, 2018.0, 2019.0, 2020.0, 2021.0, 2022.0, 2023.0, 2024.0, 2025.0, 2026.0,
    # Common ranks / top N / calendar days (1-31) and months (1-12)
    *[float(i) for i in range(1, 32)],
    # Scale ranges (e.g. CSAT 1 to 5 scale, 100 percent)
    100.0
}


def normalize_multilingual_numbers(text: str) -> str:
    """
    Normalizes Devanagari numerals (०-९ -> 0-9) and expands South Asian
    number scale words (lakh, crore, hazaar in Hindi/English).
    """
    if not text:
        return ""

    # 1. Translate Devanagari digits to standard ASCII Arabic digits
    normalized = text.translate(DEV_TO_ARABIC)

    # 2. Expand crore / करोड़ / cr
    def _crore_repl(m):
        try:
            val = float(m.group(1).replace(",", ""))
            return f" {val * 10000000.0:.2f} "
        except ValueError:
            return m.group(0)

    normalized = re.sub(
        r'(\d+(?:,\d+)*(?:\.\d+)?)\s*(?:करोड़|करोड|crores?|cr\b)',
        _crore_repl,
        normalized,
        flags=re.IGNORECASE
    )

    # 3. Expand lakh / लाख / lac
    def _lakh_repl(m):
        try:
            val = float(m.group(1).replace(",", ""))
            return f" {val * 100000.0:.2f} "
        except ValueError:
            return m.group(0)

    normalized = re.sub(
        r'(\d+(?:,\d+)*(?:\.\d+)?)\s*(?:लाख|lakhs?|lacs?\b)',
        _lakh_repl,
        normalized,
        flags=re.IGNORECASE
    )

    # 4. Expand hazaar / हज़ार / hazar
    def _hazaar_repl(m):
        try:
            val = float(m.group(1).replace(",", ""))
            return f" {val * 1000.0:.2f} "
        except ValueError:
            return m.group(0)

    normalized = re.sub(
        r'(\d+(?:,\d+)*(?:\.\d+)?)\s*(?:हज़ार|हजार|hazaars?|hazars?\b)',
        _hazaar_repl,
        normalized,
        flags=re.IGNORECASE
    )

    return normalized


def extract_numbers_from_text(text: str) -> List[float]:
    """
    Extract all numeric values from a string, handling Devanagari digits,
    currency symbols, Indian and Western comma formats, lakh/crore, and percentages.
    """
    if not text:
        return []

    norm_text = normalize_multilingual_numbers(text)
    extracted: List[float] = []

    for match in NUMBER_REGEX.finditer(norm_text):
        raw_num = match.group(1)
        is_pct = bool(match.group(2))

        # Remove thousand separator commas
        cleaned = raw_num.replace(",", "")
        try:
            val = float(cleaned)
            extracted.append(val)
            # If formatted with a percent symbol (e.g. 15.2%), also add the 0.0-1.0 fraction
            if is_pct:
                extracted.append(round(val / 100.0, 6))
        except ValueError:
            continue

    return extracted


def extract_numbers_from_evidence(data: Any) -> Set[float]:
    """
    Recursively traverse evidence payload (dicts, lists, primitives) and extract
    all numbers, including their percent/fraction equivalents.
    """
    nums: Set[float] = set()

    def _traverse(node: Any):
        if node is None:
            return
        elif isinstance(node, (int, float)):
            val = float(node)
            nums.add(val)
            # Add rounded variants
            nums.add(round(val, 2))
            nums.add(round(val, 4))
            # Also add percent <-> fraction conversions
            if 0.0 <= val <= 1.0:
                nums.add(round(val * 100.0, 2))
            elif 0.0 <= val <= 100.0:
                nums.add(round(val / 100.0, 4))
        elif isinstance(node, str):
            for n in extract_numbers_from_text(node):
                nums.add(n)
                nums.add(round(n, 2))
        elif isinstance(node, dict):
            for v in node.values():
                _traverse(v)
        elif isinstance(node, (list, tuple, set)):
            for item in node:
                _traverse(item)

    _traverse(data)
    return nums


def verify_numeric_grounding(
    answer: str,
    evidence_data: Any,
    tolerance_pct: float = 1.0
) -> bool:
    """
    Numeric Faithfulness Verifier:
    Extracts all numeric tokens from the LLM generated answer and verifies that
    each number appears in the computed evidence payload within tolerance.

    Parameters:
      - answer: The natural language string generated by the LLM
      - evidence_data: Raw analytics payload dictionary/list
      - tolerance_pct: Maximum relative error percentage allowed for rounding (default: 1.0%)

    Returns:
      - True if all non-structural numbers in the answer are grounded in evidence.
      - False if any number is ungrounded / hallucinated.
    """
    answer_numbers = extract_numbers_from_text(answer)
    if not answer_numbers:
        return True

    evidence_numbers = extract_numbers_from_evidence(evidence_data)
    if not evidence_numbers:
        # If there are specific metrics mentioned in the answer but zero evidence numbers, fail
        non_metadata = [n for n in answer_numbers if n not in COMMON_METADATA_NUMBERS]
        return len(non_metadata) == 0

    for num in answer_numbers:
        # Allow common metadata, ranks, and dataset years
        if num in COMMON_METADATA_NUMBERS:
            continue

        matched = False
        for ev in evidence_numbers:
            # 1. Direct small absolute difference (e.g. rounding within 0.05)
            if abs(num - ev) <= 0.05:
                matched = True
                break

            # 2. Percentage scaling match (e.g. 15.2 vs 0.152 or 92.5 vs 0.925)
            if abs(num - (ev * 100.0)) <= 0.05 or abs((num / 100.0) - ev) <= 0.0005:
                matched = True
                break

            # 3. Relative tolerance check
            if abs(ev) > 0.01:
                rel_err = abs(num - ev) / abs(ev) * 100.0
                if rel_err <= tolerance_pct:
                    matched = True
                    break

        if not matched:
            logger.warning(
                f"Numeric grounding check FAILED: number '{num}' in answer not found in evidence payload."
            )
            return False

    return True
